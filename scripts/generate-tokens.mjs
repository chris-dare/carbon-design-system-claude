// Generates src/tokens/*.js with literal values read from the Carbon
// packages, so the token files are explicit and readable while staying
// exactly in sync with the installed @carbon version.
import { writeFileSync, mkdirSync } from 'node:fs';
import { white, g10, g90, g100 } from '@carbon/themes';
import * as colors from '@carbon/colors';
import * as type from '@carbon/type';
import * as layout from '@carbon/layout';

const OUT = new URL('../src/tokens/', import.meta.url);
mkdirSync(OUT, { recursive: true });
const banner = `// AUTO-GENERATED by scripts/generate-tokens.mjs — do not edit by hand.\n// Source: @carbon/themes, @carbon/colors, @carbon/type, @carbon/layout.\n\n`;
const write = (f, s) => writeFileSync(new URL(f, OUT), banner + s);
const lit = (v) => JSON.stringify(v, null, 2);

// --- Themes: the four Carbon themes, 235 semantic tokens each ---------------
write('themes.js', `export const themes = {
  white: ${lit(white)},
  g10: ${lit(g10)},
  g90: ${lit(g90)},
  g100: ${lit(g100)}
};

export const themeNames = ['white', 'g10', 'g90', 'g100'];
export default themes;
`);

// --- Colors: the raw swatch palette ----------------------------------------
const swatches = Object.fromEntries(
  Object.entries(colors).filter(([k, v]) => typeof v === 'string' && v.startsWith('#'))
);
write('colors.js', `export const colors = ${lit(swatches)};\nexport default colors;\n`);

// --- Typography: the Carbon type scale -------------------------------------
const styles = Object.fromEntries(
  Object.entries(type).filter(([k, v]) => v && typeof v === 'object' && 'fontSize' in v)
);
write('typography.js', `export const fontFamilies = {
  sans: "'IBM Plex Sans', 'Helvetica Neue', Arial, sans-serif",
  serif: "'IBM Plex Serif', Georgia, serif",
  mono: "'IBM Plex Mono', Menlo, 'DejaVu Sans Mono', monospace"
};

export const typeStyles = ${lit(styles)};
export default typeStyles;
`);

// --- Spacing + layout ------------------------------------------------------
const pick = (pre) => Object.fromEntries(
  Object.entries(layout).filter(([k, v]) => k.startsWith(pre) && typeof v === 'string')
);
write('spacing.js', `export const spacing = ${lit(pick('spacing'))};
export const fluidSpacing = ${lit(pick('fluidSpacing'))};
export const sizes = ${lit(pick('size'))};
export default spacing;
`);

console.log('tokens written:', Object.keys(swatches).length, 'colors,',
  Object.keys(styles).length, 'type styles,', Object.keys(pick('spacing')).length, 'spacing steps');
